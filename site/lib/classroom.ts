function contractorsPack(): DataPack {
  const rows: Cell[][] = [];
  const push = (scope: string, list: typeof privateData.contractors, hasYtd: boolean) => {
    list.forEach((c, i) => rows.push([
      scope, i + 1, c.name, c[completed] as number, (c[prior] as number) ?? null, round(c.growth),
      hasYtd ? ((c[`${current}ytd`] as number) ?? null) : null, c.source,
    ]));
  };
  push("North Carolina (top 100)", privateData.contractors, true);
  for (const [county, list] of Object.entries(privateData.localContractors)) push(`${county} County (top 25)`, list, false);
  return {
    slug: "nc-federal-contractors",
    title: "Federal contractors in North Carolina",
    summary: `The largest federal contract recipients with a North Carolina address in ${completed}, plus the top 25 in Mecklenburg and Union counties, with the year before for comparison.`,
    source: { label: "USAspending.gov API (spending by recipient, contracts only)", href: "https://www.usaspending.gov/search" },
    goodFor: ["Concentration (how much goes to the biggest few)", "Year-over-year change", "Civics: following public money"],
    columns: [
      { name: "scope", meaning: "Which ranking the row belongs to: statewide top 100, or a county's top 25" },
      { name: "rank", meaning: `Rank by ${completed} obligations within that scope` },
      { name: "contractor", meaning: "Recipient name in USAspending" },
      { name: `obligations_${completed}_usd`, meaning: `Contract dollars the government committed in federal ${completed} (October to September)` },
      { name: `obligations_${prior}_usd`, meaning: `Same, for ${prior}. Blank if the recipient was not in that year's ranking` },
      { name: "change_ratio", meaning: `(${completed} − ${prior}) ÷ ${prior}. 0.25 means up 25%. Blank if there is no ${prior} figure` },
      { name: `obligations_${current}_to_date_usd`, meaning: `${current} so far (statewide rows only)` },
      { name: "source_url", meaning: "Recipient profile on USAspending.gov" },
    ],
    rows,
  };
}

