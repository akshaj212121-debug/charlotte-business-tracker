// Classroom data packs: flat CSV versions of the site's public-record data, built at the same time as the site,
// so a monthly data refresh updates the downloads too. No figure here is computed beyond simple arithmetic on
// filed values (sums, shares, percent change), and every row carries a link to its source record.
import { companies, inRegion, nonprofits, privateData, warnNotices } from "@/lib/data";

type Cell = string | number | boolean | null | undefined;

export interface PackColumn { name: string; meaning: string }

export interface DataPack {
  slug: string; // URL segment, also the file name without .csv
  title: string;
  summary: string;
  source: { label: string; href: string };
  columns: PackColumn[];
  rows: Cell[][];
  goodFor: string[];
}

const csvCell = (v: Cell) => {
  if (v == null) return "";
  const s = String(v);
  return /[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};

export function toCsv(pack: DataPack): string {
  const lines = [pack.columns.map((c) => c.name), ...pack.rows].map((r) => r.map(csvCell).join(","));
  return lines.join("\r\n") + "\r\n";
}

const round = (n: number | null | undefined, digits = 4) => (n == null || !Number.isFinite(n) ? null : Number(n.toFixed(digits)));

const { completed, prior, current } = privateData.fiscalYears;

