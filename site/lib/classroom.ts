export const dataPacks: DataPack[] = [companiesPack(), nonprofitsPack(), contractorsPack(), awardsPack(), warnPack()];

export const getPack = (slug: string) => dataPacks.find((p) => p.slug === slug);
export const packHref = (slug: string) => `/classroom/data/${slug}.csv`;

// Small helpers the worksheets use for their worked examples and answer keys.
export function median(values: number[]): number | null {
  if (!values.length) return null;
  const s = [...values].sort((a, b) => a - b);
  const m = Math.floor(s.length / 2);
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
}

export const pctChange = (now: number | null | undefined, before: number | null | undefined) =>
  now == null || before == null || before === 0 ? null : (now - before) / Math.abs(before);

export const share = (part: number | null | undefined, whole: number | null | undefined) =>
  part == null || whole == null || whole === 0 ? null : part / whole;
